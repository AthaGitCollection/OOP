package Assignment;

public class Anggota {
    private String nama;
    private String noAnggota;

    public Anggota(String nama, String noAnggota) {
        this.nama = nama;
        this.noAnggota = noAnggota;
    }

    public String getNama() {
        return nama;
    }

    public String getNoAnggota() {
        return noAnggota;
    }
}